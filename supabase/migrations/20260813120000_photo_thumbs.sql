-- Превью для фотографий.
--
-- Оригиналы весят в среднем больше мегабайта, а карта показывает их в маркерах
-- размером 20×20 — на загрузку карты уходило под 75 МБ. Теперь рядом с каждым
-- снимком лежит уменьшенная копия (в бакете photos, в папке thumbs/), а полный
-- размер грузится только там, где он действительно нужен: в карточке точки,
-- на странице находки и в игре.
--
-- Пустая строка означает «превью нет» — клиент в этом случае берёт оригинал,
-- поэтому старые записи продолжают работать до заполнения.

alter table public.details add column if not exists thumb_url text not null default '';
alter table public.photos  add column if not exists thumb_url text not null default '';
